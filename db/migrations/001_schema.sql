-- =========================================================
--  ProSiga — Schema do banco (PostgreSQL / Supabase)
--  Mesmo modelo do projeto "prova_desenvolvimento_web_2".
--  Executado pelo runner: npm run migrate
-- =========================================================

-- ---------------------------------------------------------
-- Usuários (alunos, professores e administradores)
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          VARCHAR(120) NOT NULL,
  email         VARCHAR(160) NOT NULL,
  senha         VARCHAR(255) NOT NULL,
  tipo          VARCHAR(10)  NOT NULL DEFAULT 'aluno'
                CHECK (tipo IN ('admin','professor','aluno')),
  matricula     VARCHAR(40)  DEFAULT NULL,
  setor         VARCHAR(120) DEFAULT NULL,
  token         VARCHAR(64)  DEFAULT NULL,
  ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
  criado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_usuarios_email UNIQUE (email),
  CONSTRAINT uq_usuarios_matricula UNIQUE (matricula)
);

CREATE INDEX IF NOT EXISTS idx_usuarios_tipo ON usuarios (tipo);

-- ---------------------------------------------------------
-- Turmas
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS turmas (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(120) NOT NULL,
  disciplina  VARCHAR(120) NOT NULL,
  codigo      VARCHAR(30)  NOT NULL,
  semestre    VARCHAR(20)  NOT NULL DEFAULT '2026.1',
  sala        VARCHAR(40)  DEFAULT NULL,
  capacidade  SMALLINT     NOT NULL DEFAULT 40,
  criado_por  INTEGER      DEFAULT NULL,
  criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_turmas_codigo UNIQUE (codigo),
  CONSTRAINT fk_turmas_usuario FOREIGN KEY (criado_por)
    REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_turmas_criado_por ON turmas (criado_por);

-- ---------------------------------------------------------
-- Vínculos professores x turmas / alunos x turmas
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS turma_professores (
  turma_id     INTEGER NOT NULL,
  professor_id INTEGER NOT NULL,
  vinculo_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (turma_id, professor_id),
  CONSTRAINT fk_tp_turma FOREIGN KEY (turma_id)
    REFERENCES turmas (id) ON DELETE CASCADE,
  CONSTRAINT fk_tp_professor FOREIGN KEY (professor_id)
    REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_tp_professor ON turma_professores (professor_id);

CREATE TABLE IF NOT EXISTS turma_alunos (
  turma_id   INTEGER NOT NULL,
  aluno_id   INTEGER NOT NULL,
  vinculo_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (turma_id, aluno_id),
  CONSTRAINT fk_ta_turma FOREIGN KEY (turma_id)
    REFERENCES turmas (id) ON DELETE CASCADE,
  CONSTRAINT fk_ta_aluno FOREIGN KEY (aluno_id)
    REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ta_aluno ON turma_alunos (aluno_id);

-- ---------------------------------------------------------
-- Aulas
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS aulas (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id     INTEGER NOT NULL,
  professor_id INTEGER DEFAULT NULL,
  titulo       VARCHAR(160) NOT NULL,
  data_aula    DATE NOT NULL,
  hora_inicio  TIME NOT NULL,
  hora_fim     TIME NOT NULL,
  local        VARCHAR(80) DEFAULT NULL,
  descricao    TEXT,
  criado_por   INTEGER DEFAULT NULL,
  criado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_aulas_turma FOREIGN KEY (turma_id)
    REFERENCES turmas (id) ON DELETE CASCADE,
  CONSTRAINT fk_aulas_professor FOREIGN KEY (professor_id)
    REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT fk_aulas_criador FOREIGN KEY (criado_por)
    REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_aulas_data ON aulas (data_aula);
CREATE INDEX IF NOT EXISTS idx_aulas_turma ON aulas (turma_id);

-- ---------------------------------------------------------
-- Provas
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS provas (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id     INTEGER NOT NULL,
  professor_id INTEGER DEFAULT NULL,
  titulo       VARCHAR(160) NOT NULL,
  data_prova   DATE NOT NULL,
  hora         TIME DEFAULT NULL,
  local        VARCHAR(80) DEFAULT NULL,
  peso         NUMERIC(5,2) NOT NULL DEFAULT 1.00,
  descricao    TEXT,
  criado_por   INTEGER DEFAULT NULL,
  criado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_provas_turma FOREIGN KEY (turma_id)
    REFERENCES turmas (id) ON DELETE CASCADE,
  CONSTRAINT fk_provas_professor FOREIGN KEY (professor_id)
    REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT fk_provas_criador FOREIGN KEY (criado_por)
    REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_provas_data ON provas (data_prova);
CREATE INDEX IF NOT EXISTS idx_provas_turma ON provas (turma_id);

-- ---------------------------------------------------------
-- Atividades
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS atividades (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id       INTEGER NOT NULL,
  professor_id   INTEGER DEFAULT NULL,
  titulo         VARCHAR(160) NOT NULL,
  tipo           VARCHAR(12) NOT NULL DEFAULT 'tarefa'
                 CHECK (tipo IN ('tarefa','trabalho','exercicio','projeto','outro')),
  data_entrega   DATE NOT NULL,
  hora_entrega   TIME DEFAULT NULL,
  valor          NUMERIC(5,2) NOT NULL DEFAULT 10.00,
  descricao      TEXT,
  criado_por     INTEGER DEFAULT NULL,
  criado_em      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_atividades_turma FOREIGN KEY (turma_id)
    REFERENCES turmas (id) ON DELETE CASCADE,
  CONSTRAINT fk_atividades_professor FOREIGN KEY (professor_id)
    REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT fk_atividades_criador FOREIGN KEY (criado_por)
    REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_atividades_data ON atividades (data_entrega);
CREATE INDEX IF NOT EXISTS idx_atividades_turma ON atividades (turma_id);
